/** Every code with its own hint. Other HTTP_<status> codes are described by status class. */
export const ISSUE_CODES = Object.freeze(Object.keys(ISSUES));

function lookup(code) {
  if (Object.hasOwn(ISSUES, code)) return ISSUES[code];
  const status = Number(/^HTTP_([1-5]\d\d)$/.exec(code)?.[1]);
  return status >= 500 ? SERVER_BUSY : UNKNOWN;
}

/**
 * The issue as stored ({ code, message, details? }) plus `hints` ({ en, 'zh-TW',
 * 'zh-CN' }: one next step each) and `action` (one of the actions above, or
 * null). The code always matches /^[A-Z][A-Z0-9_]{0,63}$/; a missing or
 * malformed one becomes UNKNOWN_ISSUE. Returns null when there is no issue.
 */
export function describeIssue(issue) {
  if (!issue || typeof issue !== 'object') return null;
  const raw = typeof issue.code === 'string' ? issue.code.trim().toUpperCase() : '';
  const code = CODE.test(raw) ? raw : 'UNKNOWN_ISSUE';
  const { action, hints } = lookup(code);
  return { code, message: typeof issue.message === 'string' && issue.message ? issue.message : hints['zh-TW'],
    ...(issue.details !== undefined ? { details: issue.details } : {}), hints: { ...hints }, action };
}
